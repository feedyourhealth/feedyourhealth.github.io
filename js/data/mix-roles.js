// Ρόλος ενός ονόματος: {role:'protein'|'carb'|'legume', tier:'star'|'more'|'warn'|'plant'} ή null
function mixRoleOf(name){
  var groups=['protein','carb','legume'];
  for(var i=0;i<groups.length;i++){
    var g=MIX_ROLES[groups[i]];
    for(var t in g){ if(g[t].indexOf(name)!==-1) return {role:groups[i],tier:t}; }
  }
  var fd=(typeof FOODS!=='undefined')?FOODS[name]:null;
  if(fd&&(fd.cat==='Κρέας'||fd.cat==='Ψάρια')&&typeof PORTIONS!=='undefined'&&PORTIONS[name]) return {role:'protein',tier:'more'};
  return null;
}
